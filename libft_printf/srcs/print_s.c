#include "../ft_printf.h"

int	print_s(char *str)
{
	int	i;

	i = 0;
	if (!str)
		return (write (1, "(null)", 6));
	while (str[i])
	{
		print_c(str[i]);
		i++;
	}
	return (i);
}
